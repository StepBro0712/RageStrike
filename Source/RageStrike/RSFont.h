#pragma once

#include "CoreMinimal.h"

class UFont;

// Шрифт HUD.
//
// Встроенные шрифты движка (GetSmallFont/GetMediumFont) растровые: при любом
// масштабе канваса они мылятся, и это самая заметная претензия к интерфейсу.
// Ассет FontFace /Game/UI/Fonts/FF_RSHud (Roboto-Bold) в проекте уже лежит,
// не хватало только объекта UFont поверх него — в редакторе он так и не был
// создан, а импорт TTF из Python роняет движок. Поэтому собираем UFont прямо
// в коде: FontCacheType = Runtime означает отрисовку через Slate, то есть
// векторную, без растровой сетки.
//
// Если ассет не загрузился, откатываемся на движковый шрифт: лучше мыло,
// чем HUD вообще без текста.
namespace RSFont
{
	// основной шрифт HUD; никогда не возвращает nullptr при живом GEngine
	UFont* Get();
	// крупный: заменяет GetMediumFont, пропорция кеглей та же, что была
	// у пары движковых шрифтов, чтобы вёрстка не поехала
	UFont* GetBig();
	// true, если удалось поднять векторный шрифт (для лога и диагностики)
	bool IsVector();
	// высота кегля, от которой считается масштаб текста в HUD
	int32 BaseSize();

	// Множитель к масштабу отрисовки.
	//
	// Канвас растеризует рантайм-шрифт в кеш размером ровно LegacyFontSize и
	// дальше просто масштабирует готовую картинку. Растягивание вверх мылит
	// её так же, как мылил растровый шрифт, поэтому кегль берём заведомо
	// крупный, а этим множителем ужимаем текст обратно до размера, под
	// который верстался HUD. Масштаб всегда идёт вниз — так буквы остаются
	// чёткими. Для движкового шрифта возвращает единицу.
	float RenderScale(const UFont* F);
}
